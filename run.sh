#!/bin/bash
# ==============================================================================
# PPU Complaints System - Pterodactyl Startup Script
# ==============================================================================

echo "===================================================="
echo "🏛️ نظام الشكاوى — جامعة بوليتكنك فلسطين (PPU)"
echo "🚀 جاري بدء تشغيل السيرفر الموحد على Pterodactyl..."
echo "===================================================="

# تحديد المنفذ تلقائياً من المتغير الخاص بـ Pterodactyl (SERVER_PORT)
if [ -n "$SERVER_PORT" ]; then
    export PORT=$SERVER_PORT
fi

# تثبيت الحزم تلقائياً إذا كان مجلد node_modules غير موجود
if [ ! -d "node_modules" ]; then
    echo "📦 مجلد الحزم غير موجود، جاري التثبيت عبر npm install..."
    npm install --production
fi

# تشغيل السيرفر الموحد (الفرونت إند + الباك إند على نفس المنفذ)
node index.js
